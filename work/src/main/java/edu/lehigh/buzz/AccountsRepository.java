package edu.lehigh.buzz;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;

public final class AccountsRepository {
    private final Connection connection;

    public AccountsRepository(Connection connection) {
        this.connection = connection;
    }

    public void createTable() throws SQLException {
        String sql = """
                CREATE TABLE IF NOT EXISTS accounts (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name VARCHAR(200) NOT NULL,
                    email VARCHAR(320) NOT NULL
                )
                """;
        try (Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }

    public void dropTable() throws SQLException {
        try (Statement statement = connection.createStatement()) {
            statement.execute("DROP TABLE IF EXISTS accounts");
        }
    }

    public Account createAccount(String name, String email) throws SQLException {
        String sql = "INSERT INTO accounts (name, email) VALUES (?, ?) RETURNING id";
        try (PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setString(1, name);
            statement.setString(2, email);
            try (ResultSet result = statement.executeQuery()) {
                if (!result.next()) {
                    throw new SQLException("PostgreSQL did not return the new account id.");
                }
                return new Account(result.getLong("id"), name, email);
            }
        }
    }

    public List<Account> listAccounts() throws SQLException {
        List<Account> accounts = new ArrayList<>();
        try (Statement statement = connection.createStatement();
             ResultSet result = statement.executeQuery(
                     "SELECT id, name, email FROM accounts ORDER BY id")) {
            while (result.next()) {
                accounts.add(new Account(
                        result.getLong("id"),
                        result.getString("name"),
                        result.getString("email")));
            }
        }
        return List.copyOf(accounts);
    }
}
